"""Package the existing manual integration ZIP with frozen candidate metadata."""

import argparse
import hashlib
import json
import subprocess
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

from release_version_adapter import checked_version

PREFIX = "custom_components/desloc/"


def build(root: Path, base: str, channel: str, output: Path) -> list[Path]:
    """Preserve the existing manual integration ZIP layout and exact tracked bytes."""
    checked_version(root, base, channel)
    manifest = json.loads((root / PREFIX / "manifest.json").read_text())
    if manifest.get("domain") != "desloc" or manifest.get("name") != "DESLOC":
        raise ValueError("Unexpected integration identity")
    names = sorted(
        set(
            subprocess.check_output(
                ["git", "ls-files", "-z", "--", PREFIX], cwd=root, text=True
            ).split("\0")
        )
        - {""}
    )
    if PREFIX + "manifest.json" not in names or PREFIX + "__init__.py" not in names:
        raise ValueError("Tracked integration inputs are incomplete")
    files = []
    for name in names:
        path = root / name
        if path.is_symlink() or not path.is_file():
            raise ValueError(
                "Integration inputs must be regular tracked files: " + name
            )
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            raise ValueError("Generated bytecode is not an integration source input")
        files.append((name, path.read_bytes()))
    output.mkdir(parents=True, exist_ok=True)
    if any(output.iterdir()):
        raise ValueError("Release output must be empty")
    path = output / "ha-desloc.zip"
    with ZipFile(path, "w", compression=ZIP_DEFLATED, compresslevel=9) as archive:
        for member, contents in files:
            info = ZipInfo(member, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, contents)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    (output / "SHA256SUMS").write_text(f"{digest}  {path.name}\n")
    return [path]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("base")
    parser.add_argument("channel", choices=("beta", "rc", "nightly"))
    parser.add_argument("--output", type=Path, default=Path("release-dist"))
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    for path in build(root, args.base, args.channel, args.output):
        print(path)


if __name__ == "__main__":
    main()
